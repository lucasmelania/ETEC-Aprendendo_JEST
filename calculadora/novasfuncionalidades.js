function quadrado(n1) {
  let quadrado = n1 * n1;
  return quadrado;
}

function areaTriangulo(base, altura) {
  let calcArea = (base * altura) / 2;
  return calcArea;
}

function porcentagem(n1) {
  let porcentagem = n1 * 0.1;
  return porcentagem;
}

export { quadrado, areaTriangulo, porcentagem };
